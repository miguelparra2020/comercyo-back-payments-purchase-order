import { Hono } from 'hono';
import { cors } from 'hono/cors';
import { swaggerUI } from '@hono/swagger-ui';
import { OpenAPIHono } from '@hono/zod-openapi';
import { logger } from './middlewares/logger';
import { config } from './config/config';
import { requireAuth } from './middlewares/auth.middleware';
import { rateLimiter } from './middlewares/rate-limit.middleware';
import { requireOrderAccess } from './middlewares/require-order-access.middleware';
import { registerPaymentReceiptsRoutes } from './routes/payment-receipts.routes';

const app = new Hono();
const apiV1 = new OpenAPIHono({
  defaultHook: (result, c) => {
    if ('error' in result) {
      return c.json(
        { success: false, error: 'Bad Request', message: result.error.issues[0]?.message },
        400
      );
    }
  },
});

// CORS middleware
app.use('*', cors({
  origin: config.cors.origin,
  allowHeaders: ['Content-Type', 'Authorization'],
  allowMethods: ['GET', 'POST', 'PATCH', 'PUT', 'DELETE', 'OPTIONS'],
  maxAge: 600,
  // Auth is a Bearer token, not cookies, so no request needs credentials
  // mode - and the fetch spec forbids Access-Control-Allow-Origin: * paired
  // with Access-Control-Allow-Credentials: true for a credentialed request.
  credentials: config.cors.origin !== '*',
}));

// Logger middleware
app.use('*', logger());

// Bearer JWT auth - lets Swagger UI's "Authorize" button attach
// `Authorization: Bearer <token>` to every request, and documents that
// every payment-receipt operation requires it (see `security` on each route).
apiV1.openAPIRegistry.registerComponent('securitySchemes', 'Bearer', {
  type: 'http',
  scheme: 'bearer',
  bearerFormat: 'JWT',
});

// The OpenAPI documentation will be auto-generated by @hono/zod-openapi
apiV1.doc('/openapi.json', {
  openapi: '3.0.0',
  info: {
    title: 'Comercyo Purchase Order Payments API',
    version: '1.0.0',
    description: 'CRUD de imágenes de comprobantes de pago de órdenes de compra, guardadas en un bucket privado de Cloudflare R2 y servidas con URLs firmadas temporales.',
  },
  servers: [
    {
      url: `${config.productionUrl}/api/v1`,
      description: 'Production server',
    },
    {
      url: `http://localhost:${config.port}/api/v1`,
      description: 'Development server',
    },
  ],
});

apiV1.get('/doc', swaggerUI({ url: '/api/v1/openapi.json' }));

// Best-effort abuse mitigation ahead of auth - see rate-limit.middleware.ts
// for why this is per-warm-instance rather than a global guarantee.
//
// A single '/purchase-orders/*' registration covers every receipt route,
// since all of them live under /purchase-orders/{orderId}/payments.
const paymentsRateLimiter = rateLimiter({ windowMs: 60_000, max: 100 });
apiV1.use('/purchase-orders/*', paymentsRateLimiter);
apiV1.use('/purchase-orders/*', requireAuth());
// Only the owner of the order's project may touch its receipts. The
// wildcard also matches the bare '/payments' collection path.
apiV1.use('/purchase-orders/:orderId/payments/*', requireOrderAccess());
registerPaymentReceiptsRoutes(apiV1);

app.route('/api/v1', apiV1);

// 404 handler
app.notFound((c) => {
  return c.json({
    success: false,
    error: 'Not Found',
    path: c.req.path
  }, 404);
});

// Error handler
app.onError((err, c) => {
  console.error('Unhandled error:', err);
  return c.json({
    success: false,
    error: 'Internal Server Error',
    message: err.message
  }, 500);
});

export default app;
